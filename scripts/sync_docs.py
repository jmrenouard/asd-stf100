#!/usr/bin/env python3
"""sync_docs.py - Generate reference Markdown docs and skill assets from spec/*.json.

Reads spec/rules.json, spec/categories.json, spec/dictionary.json, and
src/asd_stf100/stf_check.py to deterministically generate:
- docs/03-reference/regles-redaction.md
- docs/03-reference/dictionnaire-stf.md
- docs/03-reference/categories-techniques.md
- skills/francais-technique-simplifie/references/regles-redaction.md
- skills/francais-technique-simplifie/references/dictionnaire-stf.md
- skills/francais-technique-simplifie/references/substitutions.md
- skills/francais-technique-simplifie/scripts/stf_check.py

Usage:
    python scripts/sync_docs.py [--check] [--root PATH]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

GENERATED_BANNER = (
    "<!-- Generated by scripts/sync_docs.py from spec/*.json. Do not edit manually. -->"
)


def _cell(value: str) -> str:
    """Sanitize a string for single-line Markdown table cells."""
    return " ".join(value.replace("|", "\\|").splitlines()).strip()


def _format_inline_quote(value: str) -> str:
    """Format multi-line examples cleanly for Markdown blockquotes or cells."""
    return " / ".join(line.strip() for line in value.splitlines() if line.strip())


def render_rules_md(rules_data: dict, cat_link: str, dict_link: str) -> str:
    """Render all 9 writing rule sections (53 rules) and 8 General Recommendations."""
    meta = rules_data["meta"]
    sections = rules_data["sections"]
    grs = rules_data["general_recommendations"]
    total_rules = sum(len(s["rules"]) for s in sections)

    lines: list[str] = [
        GENERATED_BANNER,
        "",
        f"# Règles de rédaction {meta['code']} ({meta['issue']})",
        "",
        f"Référence normative complète des **{total_rules} règles** (Sections 1 à 9) et des "
        f"**{len(grs)} recommandations générales** (`GR-1` à `GR-{len(grs)}`) du {meta['title']}.",
        "",
        f"Voir aussi : [Catégories techniques]({cat_link}) | [Dictionnaire contrôlé]({dict_link}).",
        "",
        "## Métadonnées de spécification",
        "",
        "| Champ | Valeur |",
        "|---|---|",
        f"| Norme | `{_cell(meta['code'])}` — {_cell(meta['title'])} |",
        f"| Édition / Version | {_cell(meta['issue'])} (`{_cell(meta['version'])}`) |",
        f"| Date | `{_cell(meta['date'])}` |",
        f"| Inspiration méthodologique | {_cell(meta['inspired_by'])} (non affilié à ASD) |",
        f"| Licence code / spécification | `{_cell(meta['license_code'])}` / `{_cell(meta['license_spec'])}` |",
        "",
        "## Synthèse des 9 sections",
        "",
        "| Section | Intitulé | Plage | Règles |",
        "|---|---|---|---|",
    ]
    for sec in sections:
        ids = [r["id"] for r in sec["rules"]]
        plage = f"{ids[0]} – {ids[-1]}" if len(ids) > 1 else ids[0]
        lines.append(
            f"| Section {sec['number']} | {_cell(sec['title'])} | `{plage}` | {len(ids)} |"
        )
    lines.append("")

    for sec in sections:
        lines.extend(
            [
                f"## Section {sec['number']} : {sec['title']}",
                "",
                sec["intro"],
                "",
            ]
        )
        for rule in sec["rules"]:
            lines.extend(
                [
                    f"### Règle {rule['id']} — {rule['title']}",
                    "",
                    f"**Énoncé :** {rule['statement']}",
                    "",
                    rule["explanation"],
                    "",
                ]
            )
            if rule.get("examples"):
                lines.extend(
                    [
                        "| Non-STF | STF conforme | Remarque |",
                        "|---|---|---|",
                    ]
                )
                for ex in rule["examples"]:
                    lines.append(
                        f"| {_cell(_format_inline_quote(ex['non_stf']))} "
                        f"| {_cell(_format_inline_quote(ex['stf']))} "
                        f"| {_cell(ex.get('note', '—'))} |"
                    )
                lines.append("")

    lines.extend(
        [
            "## Recommandations générales (GR-1 à GR-8)",
            "",
            "| ID | Intitulé | Règle pratique | Non-STF | STF conforme |",
            "|---|---|---|---|---|",
        ]
    )
    for gr in grs:
        ex = gr["examples"][0] if gr.get("examples") else {"non_stf": "—", "stf": "—"}
        lines.append(
            f"| `{gr['id']}` | {_cell(gr['title'])} | {_cell(gr['statement'])} "
            f"| {_cell(_format_inline_quote(ex['non_stf']))} "
            f"| {_cell(_format_inline_quote(ex['stf']))} |"
        )
    lines.append("")
    return "\n".join(lines)


def render_categories_md(cats_data: dict, rules_link: str, dict_link: str) -> str:
    """Render the 22 technical noun categories and 4 technical verb categories."""
    noun_cats = cats_data["technical_noun_categories"]
    verb_cats = cats_data["technical_verb_categories"]

    lines: list[str] = [
        GENERATED_BANNER,
        "",
        "# Catégories techniques autorisées (ASD-STF100)",
        "",
        f"Référence officielle des **{len(noun_cats)} catégories de noms techniques** (Règle 1.5) "
        f"et des **{len(verb_cats)} catégories de verbes techniques** (Règle 1.12).",
        "",
        f"Voir aussi : [Règles de rédaction]({rules_link}) | [Dictionnaire contrôlé]({dict_link}).",
        "",
        f"## Les {len(noun_cats)} catégories de noms techniques (Règle 1.5)",
        "",
        "| ID | Catégorie | Description | Exemples autorisés |",
        "|---|---|---|---|",
    ]
    for cat in noun_cats:
        ex_str = ", ".join(f"`{e}`" for e in cat["examples"])
        lines.append(
            f"| {cat['id']} | **{_cell(cat['title'])}** | {_cell(cat['description'])} | {ex_str} |"
        )
    lines.extend(
        [
            "",
            f"## Les {len(verb_cats)} catégories de verbes techniques (Règle 1.12)",
            "",
            "Employez un verbe technique uniquement si aucun verbe du dictionnaire approuvé "
            "n'exprime exactement l'action métier requise.",
            "",
            "| ID | Catégorie | Sous-catégorie | Exemples de verbes |",
            "|---|---|---|---|",
        ]
    )
    for cat in verb_cats:
        for sub in cat["subcategories"]:
            ex_str = ", ".join(f"`{e}`" for e in sub["examples"])
            lines.append(
                f"| {cat['id']}{sub['code']} | **{_cell(cat['title'])}** "
                f"| {_cell(sub['title'])} | {ex_str} |"
            )
    lines.append("")
    return "\n".join(lines)


def render_dictionary_md(dict_data: dict, rules_link: str, extra_link_label: str, extra_link: str) -> str:
    """Render the controlled French dictionary in a parseable Markdown format."""
    entries = dict_data["entries"]
    approved = [e for e in entries if e["approved"]]
    unapproved = [e for e in entries if not e["approved"]]
    verbs = [e for e in approved if e["pos"] == "v"]
    approved_ant = dict_data["meta"]["approved_ant"]
    recurring = dict_data["recurring_errors"]

    lines: list[str] = [
        GENERATED_BANNER,
        "",
        "# Dictionnaire contrôlé ASD-STF100",
        "",
        f"Voir aussi : [Règles de rédaction]({rules_link}) | [{extra_link_label}]({extra_link}).",
        "",
        "## Statistiques du vocabulaire",
        "",
        "| Indicateur | Effectif |",
        "|---|---|",
        f"| Entrées approuvées | {len(approved)} |",
        f"| Verbes approuvés | {len(verbs)} |",
        f"| Mots non approuvés documentés | {len(unapproved)} |",
        f"| Erreurs récurrentes | {len(recurring)} |",
        f"| Mots en `-ant` approuvés (Règle 3.5) | {len(approved_ant)} |",
        "",
        "## Mots en -ant approuvés (Règle 3.5)",
        "",
        "| Mot | Catégorie |",
        "|---|---|",
    ]
    for word in approved_ant:
        lines.append(f"| `{word}` | mot en `-ant` approuvé |")

    lines.extend(
        [
            "",
            "## Entrées approuvées",
            "",
            "| Mot | Cat. | Formes fléchies | Sens approuvé | Exemple STF |",
            "|---|---|---|---|---|",
        ]
    )
    for e in approved:
        forms = ", ".join(e["forms"]) if e["forms"] else "—"
        lines.append(
            f"| `{_cell(e['word'])}` | {_cell(e['pos'])} | {_cell(forms)} "
            f"| {_cell(e['meaning'])} | {_cell(e['stf_example'])} |"
        )

    lines.extend(
        [
            "",
            "## Entrées non approuvées et remplacements",
            "",
            "| Mot non approuvé | Cat. | Formes | Remplacements STF | Exemple non-STF | Exemple STF |",
            "|---|---|---|---|---|---|",
        ]
    )
    for e in unapproved:
        forms = ", ".join(e["forms"]) if e["forms"] else "—"
        alts = ", ".join(e["alternatives"])
        lines.append(
            f"| `{_cell(e['word'])}` | {_cell(e['pos'])} | {_cell(forms)} "
            f"| {_cell(alts)} | {_cell(e['non_stf_example'])} | {_cell(e['stf_example'])} |"
        )

    lines.extend(
        [
            "",
            "## Erreurs récurrentes",
            "",
            "| Expression non-STF | Équivalent STF |",
            "|---|---|",
        ]
    )
    for err in recurring:
        lines.append(f"| {_cell(err['non_stf'])} | {_cell(err['stf'])} |")
    lines.append("")
    return "\n".join(lines)


def render_substitutions_md(dict_data: dict, cats_data: dict) -> str:
    """Render skill substitutions.md combining unapproved replacements, recurring errors, and categories."""
    unapproved = [e for e in dict_data["entries"] if not e["approved"]]
    recurring = dict_data["recurring_errors"]
    noun_cats = cats_data["technical_noun_categories"]
    verb_cats = cats_data["technical_verb_categories"]

    lines: list[str] = [
        GENERATED_BANNER,
        "",
        "# Remplacements et catégories techniques (ASD-STF100)",
        "",
        "Ce guide réunit les substitutions lexicales recommandées, les erreurs récurrentes "
        "et la table des catégories techniques autorisées. Voir aussi : "
        "[Règles de rédaction](regles-redaction.md) | [Dictionnaire contrôlé](dictionnaire-stf.md).",
        "",
        "## Partie 1 : Remplacements des mots non approuvés et erreurs récurrentes",
        "",
        "### Mots non approuvés fréquents",
        "",
        "| Mot non approuvé | Cat. | Remplacements STF | Exemple non-STF | Exemple STF |",
        "|---|---|---|---|---|",
    ]
    for e in unapproved:
        alts = ", ".join(e["alternatives"])
        lines.append(
            f"| `{_cell(e['word'])}` | {_cell(e['pos'])} | {_cell(alts)} "
            f"| {_cell(e['non_stf_example'])} | {_cell(e['stf_example'])} |"
        )

    lines.extend(
        [
            "",
            "### Expressions et erreurs récurrentes",
            "",
            "| Tournure non-STF | Équivalent STF |",
            "|---|---|",
        ]
    )
    for err in recurring:
        lines.append(f"| {_cell(err['non_stf'])} | {_cell(err['stf'])} |")

    lines.extend(
        [
            "",
            f"## Partie 2 : Les {len(noun_cats)} catégories de noms techniques (Règle 1.5)",
            "",
            "| ID | Catégorie | Description | Exemples |",
            "|---|---|---|---|",
        ]
    )
    for cat in noun_cats:
        ex_str = ", ".join(f"`{e}`" for e in cat["examples"])
        lines.append(
            f"| {cat['id']} | **{_cell(cat['title'])}** | {_cell(cat['description'])} | {ex_str} |"
        )

    lines.extend(
        [
            "",
            f"## Partie 3 : Les {len(verb_cats)} catégories de verbes techniques (Règle 1.12)",
            "",
            "| ID | Catégorie | Sous-catégorie | Exemples |",
            "|---|---|---|---|",
        ]
    )
    for cat in verb_cats:
        for sub in cat["subcategories"]:
            ex_str = ", ".join(f"`{e}`" for e in sub["examples"])
            lines.append(
                f"| {cat['id']}{sub['code']} | **{_cell(cat['title'])}** "
                f"| {_cell(sub['title'])} | {ex_str} |"
            )
    lines.append("")
    return "\n".join(lines)


def build_expected_files(repo_root: Path) -> dict[Path, str]:
    """Compute exact expected file contents for all generated docs and skill files."""
    spec_dir = repo_root / "spec"
    rules_data = json.loads((spec_dir / "rules.json").read_text(encoding="utf-8"))
    cats_data = json.loads((spec_dir / "categories.json").read_text(encoding="utf-8"))
    dict_data = json.loads((spec_dir / "dictionary.json").read_text(encoding="utf-8"))
    linter_src = (
        repo_root / "src" / "asd_stf100" / "stf_check.py"
    ).read_text(encoding="utf-8").replace("\r\n", "\n")

    docs_ref = repo_root / "docs" / "03-reference"
    skill_ref = repo_root / "skills" / "francais-technique-simplifie" / "references"
    skill_scripts = repo_root / "skills" / "francais-technique-simplifie" / "scripts"

    return {
        docs_ref / "regles-redaction.md": render_rules_md(
            rules_data, "categories-techniques.md", "dictionnaire-stf.md"
        ),
        docs_ref / "categories-techniques.md": render_categories_md(
            cats_data, "regles-redaction.md", "dictionnaire-stf.md"
        ),
        docs_ref / "dictionnaire-stf.md": render_dictionary_md(
            dict_data, "regles-redaction.md", "Catégories techniques", "categories-techniques.md"
        ),
        skill_ref / "regles-redaction.md": render_rules_md(
            rules_data, "substitutions.md", "dictionnaire-stf.md"
        ),
        skill_ref / "dictionnaire-stf.md": render_dictionary_md(
            dict_data, "regles-redaction.md", "Remplacements et catégories", "substitutions.md"
        ),
        skill_ref / "substitutions.md": render_substitutions_md(dict_data, cats_data),
        skill_scripts / "stf_check.py": linter_src,
    }


def sync(repo_root: Path, check_only: bool = False) -> int:
    """Write or verify all generated files. Returns 0 when in sync, 1 on mismatch."""
    expected = build_expected_files(repo_root)
    drifts: list[Path] = []
    for path, content in expected.items():
        if check_only:
            if not path.is_file():
                drifts.append(path)
                continue
            current = path.read_text(encoding="utf-8").replace("\r\n", "\n")
            if current != content:
                drifts.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(content)

    if check_only:
        if drifts:
            for p in drifts:
                print(f"OUT OF SYNC: {p.relative_to(repo_root)}", file=sys.stderr)
            return 1
        print(f"All {len(expected)} generated files are in sync.")
        return 0

    print(f"Synchronized {len(expected)} files from spec/*.json and stf_check.py.")
    return 0


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint for sync_docs.py."""
    ap = argparse.ArgumentParser(
        description="Synchronize generated reference docs and skill files from spec/*.json."
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify generated files match spec/*.json without modifying disk",
    )
    ap.add_argument(
        "--root",
        default=None,
        help="repository root path (defaults to parent of scripts/)",
    )
    args = ap.parse_args(argv)
    root = Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[1]
    return sync(root, check_only=args.check)


if __name__ == "__main__":
    sys.exit(main())
